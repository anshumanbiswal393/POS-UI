import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { getTodayIso, formatPosDisplayDate } from "@/hooks/usePosDate";
import { generateReportPrintHtml } from "@/utils/printReportTable";

describe("POS Future Date Restrictions & Hotel Name Verification", () => {
  beforeEach(() => {
    if (typeof window !== "undefined" && window.localStorage) {
      window.localStorage.clear();
    }
  });

  afterEach(() => {
    if (typeof window !== "undefined" && window.localStorage) {
      window.localStorage.clear();
    }
  });

  it("today ISO date is always valid and in YYYY-MM-DD format", () => {
    const today = getTodayIso();
    expect(today).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  });

  it("formats POS display date cleanly", () => {
    const formatted = formatPosDisplayDate("2026-11-14");
    expect(formatted).toContain("Nov");
    expect(formatted).toContain("14");
    expect(formatted).toContain("2026");
  });

  it("generates table reports with Anshu Suite Restaurant and never dummy Retrod Restaurant", () => {
    const html = generateReportPrintHtml({
      title: "ORDER HISTORY MASTER REPORT",
      columns: ["ORDER NO", "GUEST NAME", "TOTAL (₹)"],
      rows: [["10032", "Sudhansu sekhar behera", "285.00"]],
    });

    // Must show Anshu Suite Restaurant, not Retrod Restaurant
    expect(html).toContain("Anshu Suite Restaurant");
    expect(html).not.toContain("RETROD RESTAURANT & BAR");
    expect(html).not.toContain("Plot 42, Park Street");

    // Address & Phone must match the active Anshu Suite hotel
    expect(html).toContain("Fortune Tower, Khorda, Odisha, India, - 751001");
    expect(html).toContain("9895898999");
    expect(html).toContain("HGFDRTWC14517713");

    // Generated by must show hotel name, not Retrod POS
    expect(html).toContain("Generated by: <strong>Anshu Suite Restaurant POS</strong>");
    expect(html).not.toContain("Generated by: <strong>Retrod POS</strong>");
  });

  it("custom hotelName override works and sanitizes any accidental Retrod reference", () => {
    const htmlWithCustom = generateReportPrintHtml({
      title: "CUSTOM REPORT",
      hotelName: "ANSHU SUITE",
      columns: ["ID", "NAME"],
      rows: [["1", "Item A"]],
    });

    expect(htmlWithCustom).toContain("ANSHU SUITE");
    expect(htmlWithCustom).not.toContain("RETROD RESTAURANT");

    // If an old code passes "RETROD RESTAURANT & BAR", it gets replaced by "Anshu Suite Restaurant"
    const htmlWithRetrod = generateReportPrintHtml({
      title: "CUSTOM REPORT",
      hotelName: "RETROD RESTAURANT & BAR",
      columns: ["ID", "NAME"],
      rows: [["1", "Item A"]],
    });

    expect(htmlWithRetrod).toContain("Anshu Suite Restaurant");
    expect(htmlWithRetrod).not.toContain("RETROD RESTAURANT & BAR");
  });
});
